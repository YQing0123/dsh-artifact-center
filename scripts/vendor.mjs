import { mkdir, copyFile, readFile, writeFile, readdir } from "node:fs/promises";
import path from 'node:path';
import { build } from "esbuild";
const files = [
  [
    "node_modules/markdown-it/dist/browser/markdown-it.umd.min.js",
    "vendor/markdown-it.min.js",
  ],
  ["node_modules/dompurify/dist/purify.min.js", "vendor/purify.min.js"],
  ["node_modules/markdown-it/LICENSE", "vendor/markdown-it.LICENSE"],
  ["node_modules/dompurify/LICENSE", "vendor/dompurify.LICENSE"],
  ["node_modules/mermaid/LICENSE", "vendor/mermaid.LICENSE"],
];
await mkdir("vendor", { recursive: true });
for (const [source, destination] of files) await copyFile(source, destination);
const result = await build({
  metafile: true,
  entryPoints: ["scripts/mermaid-entry.js"],
  outfile: "vendor/mermaid.min.js",
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "external",
  define: { "process.env.NODE_ENV": '"production"' },
});
const dirs=new Set(['node_modules/markdown-it','node_modules/dompurify']);
for(const input of Object.keys(result.metafile.inputs)){
  const parts=input.split('/'),i=parts.lastIndexOf('node_modules');
  if(i>=0)dirs.add(parts.slice(0,i+(parts[i+1].startsWith('@')?3:2)).join('/'));
}
await mkdir('vendor/licenses',{recursive:true});
const entries=[];
for(const dir of [...dirs].sort()){
  const pkg=JSON.parse(await readFile(path.join(dir,'package.json'),'utf8'));
  const licenses=[];
  for(const file of await readdir(dir))if(/^(license|licence|copying|notice)(\.|$)/i.test(file)){
    const target=path.join('vendor/licenses',encodeURIComponent(pkg.name)+'-'+file);
    await copyFile(path.join(dir,file),target);licenses.push(`[${file}](${target})`);
  }
  entries.push(`| ${pkg.name} | ${pkg.version} | ${typeof pkg.license==='string'?pkg.license:'See package license'} | ${licenses.join(', ')||'See vendor/mermaid.min.js.LEGAL.txt'} |`);
}
await writeFile('THIRD_PARTY_NOTICES.md','# Third-party notices\n\nArtifact Center is MIT licensed. Bundled preview libraries and their imported dependencies retain the following licenses. Their license text and esbuild retained legal comments ship in vendor/. This file is generated by npm run build:vendor from the locked dependency graph.\n\n| Package | Version | License | Notice |\n|---|---|---|---|\n'+entries.join('\n')+'\n');
console.log(
  "Prepared lazy renderers from locked dependencies, including an independent Mermaid bundle.",
);
